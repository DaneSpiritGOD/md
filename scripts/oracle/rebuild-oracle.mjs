/**
 * Legacy Oracle rebuild entry (ticket 06) — thin wrapper over the capability.
 *
 * This script predates the verify gate and still writes repo paths, because
 * `packages/md-web-cli/ORACLE.md` and `.github/workflows/oracle-rebuild.yml`
 * reference it. The capture itself lives in `scripts/verify/oracle.mjs`; this
 * wrapper exists only until the committed Oracle artifacts are retired, and
 * the gate never calls it.
 */

import { existsSync } from 'node:fs'
import { mkdtemp, mkdir, readFile, rename, rm, writeFile } from 'node:fs/promises'
import { tmpdir } from 'node:os'
import { dirname, join, resolve } from 'node:path'
import process from 'node:process'
import { fileURLToPath } from 'node:url'
import { captureOracle } from '../verify/oracle.mjs'

const HERE = dirname(fileURLToPath(import.meta.url))
const REPO_ROOT = resolve(HERE, `../..`)
const FIXTURE_PATH = resolve(REPO_ROOT, `packages/md-web-cli/fixtures/full.md`)
const OUT_DIR = resolve(REPO_ROOT, `packages/md-web-cli/oracle`)
const OUT_PATH = join(OUT_DIR, `oracle.html`)
const REPORT_PATH = join(OUT_DIR, `oracle-report.json`)

async function main() {
  if (!existsSync(FIXTURE_PATH)) {
    console.error(`[oracle] FAILED: fixture not found: ${FIXTURE_PATH}`)
    process.exit(1)
  }

  // The capability refuses repo output paths by design; capture into a temp
  // directory and copy the result back for the legacy committed artifact.
  const scratch = await mkdtemp(resolve(tmpdir(), 'oracle-rebuild-'))
  try {
    const html = await captureOracle({ fixturePath: FIXTURE_PATH, outDir: scratch })
    const wrapped = `<!-- Browser Oracle (WeChat copy flow output) — generated by scripts/oracle/rebuild-oracle.mjs. Do not edit by hand. -->\n${html}\n`

    await mkdir(OUT_DIR, { recursive: true })
    const tmpOracle = `${OUT_PATH}.tmp`
    const tmpReport = `${REPORT_PATH}.tmp`
    await writeFile(tmpOracle, wrapped, `utf8`)
    await writeFile(tmpReport, JSON.stringify({
      generatedAt: new Date().toISOString(),
      fixturePath: `packages/md-web-cli/fixtures/full.md`,
      fixtureBytes: Buffer.byteLength(await readFile(FIXTURE_PATH, `utf8`), `utf8`),
      oracleBytes: Buffer.byteLength(wrapped, `utf8`),
    }, null, 2), `utf8`)
    await rename(tmpOracle, OUT_PATH)
    await rename(tmpReport, REPORT_PATH)
    console.log(`[oracle] wrote ${OUT_PATH} (${Buffer.byteLength(wrapped)} bytes)`)
    console.log(`[oracle] wrote ${REPORT_PATH}`)
  }
  finally {
    await rm(scratch, { recursive: true, force: true })
    await rm(`${OUT_PATH}.tmp`, { force: true })
    await rm(`${REPORT_PATH}.tmp`, { force: true })
  }
}

main().catch((error) => {
  console.error(`\n[oracle] FAILED: ${error?.stack ?? error?.message ?? String(error)}\n`)
  process.exit(1)
})
